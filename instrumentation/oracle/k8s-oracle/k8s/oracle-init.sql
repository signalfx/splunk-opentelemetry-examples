CREATE TABLE bank_accounts (
    account_id NUMBER(10) PRIMARY KEY,
    owner_name VARCHAR2(80) NOT NULL,
    account_type VARCHAR2(30) NOT NULL,
    balance NUMBER(12, 2) DEFAULT 0 NOT NULL CHECK (balance >= 0)
);

CREATE TABLE bank_transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account NUMBER(10) NOT NULL REFERENCES bank_accounts(account_id),
    to_account NUMBER(10) NOT NULL REFERENCES bank_accounts(account_id),
    amount NUMBER(12, 2) NOT NULL CHECK (amount > 0),
    memo VARCHAR2(120),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

