WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
    user_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO user_count FROM DBA_USERS WHERE USERNAME = 'OTEL_MONITOR';
    IF user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER otel_monitor IDENTIFIED BY monitorpass';
    END IF;
END;
/

ALTER USER otel_monitor IDENTIFIED BY monitorpass;
GRANT CREATE SESSION TO otel_monitor;
GRANT SELECT ON SYS.V_$SESSION TO otel_monitor;
GRANT SELECT ON SYS.V_$SYSSTAT TO otel_monitor;
GRANT SELECT ON SYS.V_$RESOURCE_LIMIT TO otel_monitor;
GRANT SELECT ON SYS.DBA_TABLESPACES TO otel_monitor;
GRANT SELECT ON SYS.DBA_DATA_FILES TO otel_monitor;
GRANT SELECT ON SYS.DBA_TABLESPACE_USAGE_METRICS TO otel_monitor;
GRANT SELECT ON SYS.V_$SQL TO otel_monitor;
GRANT SELECT ON SYS.V_$SQL_PLAN_STATISTICS_ALL TO otel_monitor;
GRANT SELECT ON SYS.DBA_PROCEDURES TO otel_monitor;
GRANT SELECT ON SYS.V_$LOCK TO otel_monitor;
GRANT SELECT ON SYS.V_$CONTAINERS TO otel_monitor;
GRANT SELECT ON SYS.DBA_OBJECTS TO otel_monitor;
GRANT SELECT ON SYS.V_$INSTANCE TO otel_monitor;
GRANT SELECT ON SYS.V_$DATABASE TO otel_monitor;

COMMIT;
